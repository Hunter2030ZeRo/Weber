import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp, mkdir, cp, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { openSync, closeSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { join, resolve } from 'node:path';
import { execute } from './native-desktop.mjs';
import { digest } from '../sdk/project.mjs';

const root = process.cwd(), binary = resolve(process.argv[2] ?? 'target/debug/weber-servo');
const project = join(await mkdtemp(join(tmpdir(), 'weber-vite-workflow-')), 'project');
const directory = resolve('artifacts/vite-workflow'); await mkdir(directory, { recursive: true });
const results = [], env = { ...process.env, WEBER_HOST: binary };
const run = async (name, executable, args, cwd = project) => {
  const path = join(directory, name + '.log'), fd = openSync(path, 'w');
  const child = spawn(executable, args, { cwd, env, detached: true, stdio: ['ignore', fd, fd] }); closeSync(fd);
  const timer = setTimeout(() => process.kill(-child.pid, 'SIGKILL'), 120000);
  let code;
  try { code = await new Promise((done, reject) => { child.once('error', reject); child.once('close', done); }); }
  finally { clearTimeout(timer); }
  const output = { stdout: await readFile(path, 'utf8'), stderr: '' };
  if (code !== 0) throw Object.assign(new Error(`Command failed: ${name}`), { code, ...output });
  return output;
};
await run('init', process.execPath, [resolve('sdk/cli.mjs'), 'init', project], root);
const original = await readFile(join(project, 'src/main.tsx'), 'utf8');
await mkdir(join(project, 'dependency'));
await writeFile(join(project, 'dependency/package.json'), JSON.stringify({ name: '@fixture/value', version: '1.0.0', type: 'module', exports: './index.js', types: './index.d.ts' }));
await writeFile(join(project, 'dependency/index.js'), 'export const value = "dependency";\n');
await writeFile(join(project, 'dependency/index.d.ts'), 'export declare const value: string;\n');
const pkg = JSON.parse(await readFile(join(project, 'package.json'))); pkg.dependencies['@fixture/value'] = 'file:./dependency';
await writeFile(join(project, 'package.json'), JSON.stringify(pkg, null, 2));
await run('npm-install', 'npm', ['install', '--offline', '--cache', process.env.WEBER_NPM_CACHE ?? '/tmp/weber-vite-npm-cache', '--no-audit', '--no-fund']);
await writeFile(join(project, 'src/alias.ts'), 'export const alias = "alias";\n');
const config = `import { weber } from '@weber/sdk/vite';
export default { plugins: [weber(), { name: 'fixture-transform', transform(code, id) { if (id.endsWith('main.tsx')) return code.replaceAll('__PLUGIN_LABEL__', 'plugin'); } }], resolve: { alias: { '@fixture/alias': ${JSON.stringify(join(project, 'src/alias.ts'))} } }, define: { __WORKFLOW_LABEL__: JSON.stringify('config') }, build: { sourcemap: true } };
`;
await writeFile(join(project, 'vite.config.mjs'), config);
const tsconfig = JSON.parse(await readFile(join(project, 'tsconfig.json'))); tsconfig.compilerOptions.paths['@fixture/alias'] = ['./src/alias.ts'];
await writeFile(join(project, 'tsconfig.json'), JSON.stringify(tsconfig, null, 2));
await writeFile(join(project, '.env'), 'VITE_WORKFLOW_LABEL=env\n');
await mkdir(join(project, 'public')); await writeFile(join(project, 'public/banner.txt'), 'public-resource');
const source = 'import { value } from "@fixture/value";\nimport { alias } from "@fixture/alias";\ndeclare const __WORKFLOW_LABEL__: string;\n' + original
  .replace('<h1>Counter</h1>', '<h1 id="label">{[__WORKFLOW_LABEL__, value, alias, "__PLUGIN_LABEL__", import.meta.env.VITE_WORKFLOW_LABEL].join("/")}</h1>')
  .replace('const button = document.getElementById("counter")!;', 'if (document.getElementById("label")!.textContent !== "config/dependency/alias/plugin/env") throw new Error("Vite config/plugin/alias/env/dependency missing at runtime");\n  const button = document.getElementById("counter")!;');
await writeFile(join(project, 'src/main.tsx'), source);
await run('npm-check', 'npm', ['run', 'check']);
await run('npm-package-jit', 'npm', ['run', 'package']);
const jit = JSON.parse(await readFile(join(project, 'dist/app.json')));
assert.equal(jit.nativeUnit, undefined); assert.equal(jit.engine, undefined);
await assert.rejects(access(join(project, 'dist/app.so')));
assert.equal(await readFile(join(project, 'package/application/banner.txt'), 'utf8'), 'public-resource');
assert.ok(jit.assets['/web.js.map']);
await cp(join(project, 'package'), join(project, 'package-jit'), { recursive: true });
results.push({ name: 'npm package JIT; project config/plugin/alias/env/dependency/public/sourcemap', passed: true });
await run('npm-package-aot', 'npm', ['run', 'package:aot']);
const aot = JSON.parse(await readFile(join(project, 'dist/app.json')));
assert.equal(aot.nativeUnit.file, 'app.so'); assert.ok(aot.engine.abi);
