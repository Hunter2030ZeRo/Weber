await assert.rejects(run('node-api-diagnostic', process.execPath, [join(root, 'sdk/cli.mjs'), 'build', project]), error => /Node.js runtime API/.test(error.stdout + error.stderr));
assert.equal(digest(await readFile(join(project, 'dist/app.json'))), before);
await writeFile(join(project, 'src/main.tsx'), source);
